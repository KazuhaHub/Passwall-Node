func socksHandshake(conn net.Conn, command byte, port int) error {
	if _, err := conn.Write([]byte{5, 1, 0}); err != nil {
		return err
	}
	reply := make([]byte, 2)
	if _, err := io.ReadFull(conn, reply); err != nil {
		return err
	}
	request := []byte{5, command, 0, 1, 127, 0, 0, 1, 0, 0}
	binary.BigEndian.PutUint16(request[8:], uint16(port))
	if command == 3 {
		request = []byte{5, 3, 0, 1, 0, 0, 0, 0, 0, 0}
	}
	if _, err := conn.Write(request); err != nil {
		return err
	}
	answer := make([]byte, 10)
	if _, err := io.ReadFull(conn, answer); err != nil {
		return err
	}
	if answer[1] != 0 {
		return fmt.Errorf("SOCKS reply %d", answer[1])
	}
	if command == 3 {
		binary.BigEndian.PutUint16(request[8:], binary.BigEndian.Uint16(answer[8:]))
		copy(request[4:8], answer[4:8])
		return relayAddress(conn, answer)
	}
	return nil
}

var relays = map[net.Conn]string{}

func relayAddress(conn net.Conn, answer []byte) error {
	relays[conn] = net.JoinHostPort(net.IP(answer[4:8]).String(), fmt.Sprint(binary.BigEndian.Uint16(answer[8:])))
	return nil
}

func socksTCP(socksPort, targetPort int, payload []byte) error {
	conn, err := net.DialTimeout("tcp", fmt.Sprintf("127.0.0.1:%d", socksPort), 2*time.Second)
	if err != nil {
		return err
	}
	defer conn.Close()
	_ = conn.SetDeadline(time.Now().Add(4 * time.Second))
	if err := socksHandshake(conn, 1, targetPort); err != nil {
		return err
	}
	if _, err := conn.Write(payload); err != nil {
		return err
	}
	got := make([]byte, len(payload))
	if _, err := io.ReadFull(conn, got); err != nil {
		return err
	}
	if !bytes.Equal(got, payload) {
		return fmt.Errorf("echo returned different bytes")
	}
	return nil
}

func socksUDP(socksPort, targetPort int, payload []byte) error {
	control, err := net.DialTimeout("tcp", fmt.Sprintf("127.0.0.1:%d", socksPort), 2*time.Second)
	if err != nil {
		return err
	}
	defer control.Close()
	defer delete(relays, control)
	_ = control.SetDeadline(time.Now().Add(4 * time.Second))
	if err := socksHandshake(control, 3, 0); err != nil {
		return err
	}
	relay := relays[control]
	if host, _, _ := net.SplitHostPort(relay); host == "0.0.0.0" {
		_, port, _ := net.SplitHostPort(relay)
		relay = net.JoinHostPort("127.0.0.1", port)
	}
	udp, err := net.Dial("udp", relay)
	if err != nil {
		return err
	}
	defer udp.Close()
	_ = udp.SetDeadline(time.Now().Add(3 * time.Second))
	datagram := []byte{0, 0, 0, 1, 127, 0, 0, 1, 0, 0}
	binary.BigEndian.PutUint16(datagram[8:], uint16(targetPort))
	if _, err := udp.Write(append(datagram, payload...)); err != nil {
		return err
	}
	buffer := make([]byte, 2048)
	n, err := udp.Read(buffer)
	if err != nil {
		return err
	}
	if n < 10 || !bytes.Equal(buffer[10:n], payload) {
		return fmt.Errorf("UDP echo returned different bytes")
	}
	return nil
}

func linkReached(c agentcore.Counters, key protocol.LinkKey, payload int64) bool {
	return len(c.Links) == 1 && c.Links[0].Key == key && c.Links[0].Present && c.Links[0].CounterEpoch != 0 &&
		c.Links[0].UpBytes >= payload && c.Links[0].DownBytes >= payload
}

// waitCounters polls a side's counters until ok holds. A nil collect is an
// engine whose counters this test does not read.
func waitCounters(t *testing.T, what string, collect func() (agentcore.Counters, error), dump func() string, ok func(agentcore.Counters) bool) {
	t.Helper()
	if collect == nil {
		return
	}
	deadline := time.Now().Add(15 * time.Second)
	for {
		counters, err := collect()
		if err == nil && ok(counters) {
			return
		}
		if time.Now().After(deadline) {
			t.Fatalf("%s counters never reached the payload: %+v (%v)\n%s", what, counters, err, dump())
		}
		time.Sleep(200 * time.Millisecond)
	}
}

// startMeter runs the production sing-box telemetry against the running
// process that serves artifact, with a scratch state store.
func startMeter(t *testing.T, snapshot agentcore.Snapshot, artifact agentcore.Artifact, apiListen string) func() (agentcore.Counters, error) {
	t.Helper()
	store, err := statesqlite.Open(t.Context(), filepath.Join(t.TempDir(), "state.db"))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = store.Close() })
	configBody, _ := json.Marshal(protocol.ConfigBody{Listeners: snapshot.Listeners, Transit: snapshot.Transit})
	rosterBody, _ := json.Marshal(protocol.RosterBody{Clients: snapshot.Clients})
	if err := store.SaveCoreDeployment(t.Context(), state.CoreDeployment{
		Engine: "sing-box", Version: "1.14.0", ConfigDigest: artifact.Digest, Artifact: artifact.Config,
		ConfigBody: configBody, RosterBody: rosterBody, AppliedAtMS: 1,
	}); err != nil {
		t.Fatal(err)
	}
	status := agentcore.Status{
		State: agentcore.ProcessRunning, Engine: "sing-box", Version: "1.14.0", BinaryPath: "/sing-box",
		ConfigDigest: artifact.Digest, LastChangedAt: time.Unix(2, 0),
	}
	telemetry, err := singbox.NewTelemetry(singbox.TelemetryOptions{
		Store: store, Status: func() agentcore.Status { return status }, APIListen: apiListen, APISecret: apiSecret,
	})
	if err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithCancel(t.Context())
	done := make(chan struct{})
	go func() { defer close(done); _ = telemetry.Run(ctx) }()
	t.Cleanup(func() { cancel(); <-done })
	return func() (agentcore.Counters, error) { return telemetry.Collect(ctx) }
}
