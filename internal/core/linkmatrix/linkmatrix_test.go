type engine struct {
	name   string
	binary string
	run    []string
	// compile turns a snapshot into an artifact this engine runs.
	compile func(t *testing.T, snapshot agentcore.Snapshot) compiled
}

type compiled struct {
	config []byte
	// meter, set for an engine whose counters come from the node's own
	// telemetry, starts that telemetry against the running process and
	// returns what a report would carry now.
	meter func(t *testing.T) func() (agentcore.Counters, error)
}

func engines(t *testing.T) []engine {
	var found []engine
	// The recommended Xray release: its REALITY accepts every client engine,
	// which a link needs because the entry may run either. (A restricted
	// release refuses a REALITY link-in, as it refuses a REALITY listener.)
	binary, ok := os.LookupEnv("PSP_TEST_XRAY_26627_BIN")
	if !ok {
		binary, ok = os.LookupEnv("PSP_TEST_XRAY_BIN")
	}
	if ok {
		found = append(found, engine{name: "xray", binary: binary, run: []string{"run", "-config"},
			compile: func(t *testing.T, snapshot agentcore.Snapshot) compiled {
				artifact, err := (xray.Compiler{APIListen: fmt.Sprintf("127.0.0.1:%d", policylive.FreePort(t))}).Compile(context.Background(), snapshot)
				if err != nil {
					t.Fatal(err)
				}
				return compiled{config: allowLoopback(t, artifact.Config)}
			}})
	}
	if binary, ok := os.LookupEnv("PSP_TEST_SING_BOX_BIN"); ok {
		found = append(found, engine{name: "sing-box", binary: binary, run: []string{"run", "-c"},
			compile: func(t *testing.T, snapshot agentcore.Snapshot) compiled {
				apiListen := fmt.Sprintf("127.0.0.1:%d", policylive.FreePort(t))
				artifact, err := (singbox.Compiler{APIListen: apiListen, APISecret: apiSecret}).Compile(context.Background(), snapshot)
				if err != nil {
					t.Fatal(err)
				}
				return compiled{config: artifact.Config, meter: func(t *testing.T) func() (agentcore.Counters, error) {
					return startMeter(t, snapshot, artifact, apiListen)
				}}
			}})
	}
	if len(found) == 0 {
		t.Skip("set PSP_TEST_XRAY_26627_BIN (or PSP_TEST_XRAY_BIN) and/or PSP_TEST_SING_BOX_BIN to run the link matrix")
	}
	return found
}

// allowLoopback lets Xray's freedom outbounds reach loopback, which they refuse
// for proxied traffic by default. Test-only; nothing else in the artifact moves.
func allowLoopback(t *testing.T, compiled []byte) []byte {
	t.Helper()
	var config map[string]any
	if err := json.Unmarshal(compiled, &config); err != nil {
		t.Fatal(err)
	}
	for _, outbound := range config["outbounds"].([]any) {
		outbound := outbound.(map[string]any)
		if outbound["protocol"] != "freedom" {
			continue
		}
		settings, _ := outbound["settings"].(map[string]any)
		if settings == nil {
			settings = map[string]any{}
		}
		settings["finalRules"] = []any{map[string]any{"action": "allow", "network": "tcp,udp"}}
		outbound["settings"] = settings
	}
	encoded, err := json.Marshal(config)
	if err != nil {
		t.Fatal(err)
	}
	return encoded
}

func newDecoy(t *testing.T) string {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	template := x509.Certificate{
		SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: decoyName}, DNSNames: []string{decoyName},
		NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(time.Hour),
		KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, &template, &template, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	server := httptest.NewUnstartedServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(http.StatusNoContent) }))
	server.TLS = &tls.Config{Certificates: []tls.Certificate{{Certificate: [][]byte{der}, PrivateKey: key}}, MinVersion: tls.VersionTLS13}
	server.StartTLS()
	t.Cleanup(server.Close)
	return server.Listener.Addr().String()
}

func linkPair(protocolName string, exitPort int, decoy string) (protocol.LinkIn, protocol.LinkOut) {
	key := protocol.NewLinkKey(7)
	in := protocol.LinkIn{Key: key, Listen: "127.0.0.1", Port: exitPort, Protocol: protocolName}
	out := protocol.LinkOut{Key: key, Address: "127.0.0.1", Port: exitPort, Protocol: protocolName}
	switch protocolName {
	case protocol.LinkProtocolSS2022:
		in.SS = &protocol.LinkSS{Method: "2022-blake3-aes-128-gcm", Password: linkKey}
		out.SS = &protocol.LinkSS{Method: "2022-blake3-aes-128-gcm", Password: linkKey}
	case protocol.LinkProtocolVLESSReality:
		in.Reality = &protocol.LinkRealityServer{UUID: linkUUID, PrivateKey: realityPrivate, Target: decoy,
			ServerNames: []string{decoyName}, ShortIDs: []string{"a1b2"}}
		out.Reality = &protocol.LinkRealityClient{UUID: linkUUID, PublicKey: realityPublic, ServerName: decoyName,
			ShortID: "a1b2", Fingerprint: "chrome"}
	}
	return in, out
}

// TestLinkMatrix runs an entry, an exit and an Xray client for every pairing
// of engines and every link protocol. The entry serves one Shadowsocks
// listener bound to the link, under a policy that blocks one port. Through the
// client it checks that:
//   - TCP and UDP reach the destination through the link;
//   - the policy still blocks on the entry for a listener that leaves through
//     a link (the rule split keeps the verdict), with an Xray entry's blocks
//     split per link as well (audit_egress);
//   - with the exit stopped, the connection fails rather than leaving from
//     the entry: there is no fallback to the entry's own address.
func TestLinkMatrix(t *testing.T) {
	available := engines(t)
	client, ok := os.LookupEnv("PSP_TEST_XRAY_CLIENT_BIN")
	if !ok {
		client, ok = os.LookupEnv("PSP_TEST_XRAY_26627_BIN")
	}
	if !ok {
		t.Skip("set PSP_TEST_XRAY_CLIENT_BIN (or PSP_TEST_XRAY_26627_BIN) for the client")
	}
	for _, entry := range available {
		for _, exit := range available {
			for _, linkProtocol := range []string{protocol.LinkProtocolSS2022, protocol.LinkProtocolVLESSReality} {
				t.Run(entry.name+"→"+exit.name+"/"+linkProtocol, func(t *testing.T) {
					runPair(t, entry, exit, linkProtocol, client)
				})
			}
		}
	}
}

func runPair(t *testing.T, entry, exit engine, linkProtocol, client string) {
	echo := transitlive.StartEcho(t)
	blocked := transitlive.StartEcho(t)
	decoy := newDecoy(t)
	exitPort, entryPort, socksPort := policylive.FreePort(t), policylive.FreePort(t), policylive.FreePort(t)
	in, out := linkPair(linkProtocol, exitPort, decoy)

	exitConfig := exit.compile(t, agentcore.Snapshot{Now: time.Now(), Transit: &protocol.Transit{LinksIn: []protocol.LinkIn{in}}})
	exitProcess := policylive.Start(t, exit.binary, append(exit.run, policylive.WriteFile(t, "exit.json", exitConfig.config))...)
	policylive.WaitListening(t, fmt.Sprintf("127.0.0.1:%d", exitPort), exitProcess)

	spec, err := json.Marshal(map[string]any{
		"enabled": true, "listen": "127.0.0.1", "port": entryPort, "protocol": "shadowsocks",
		"settings": fmt.Sprintf(`{"method":"2022-blake3-aes-128-gcm","password":%q,"network":"tcp,udp"}`, policylive.ServerKey),
	})
	if err != nil {
		t.Fatal(err)
	}
	// An Xray entry runs with audit_egress on, as PSP sets it for one with
	// egress bindings: the block is then split per link, and must still block.
	// sing-box records no hits, so it never gets the flag.
	auditEgress := entry.name == "xray"
	policy := &protocol.DestinationPolicy{Rules: []protocol.DestinationRule{
		{ID: "p1", Action: protocol.RuleBlock, Ports: fmt.Sprint(blocked.Port)},
	}}
	if auditEgress {
		policy.Collect, policy.AuditEgress = protocol.CollectHits, true
	}
	entrySnapshot := policylive.Snapshot(policy, spec)
	entrySnapshot.Transit = &protocol.Transit{
		LinksOut: []protocol.LinkOut{out},
		Egress:   []protocol.EgressBinding{{Listener: protocol.NewListenerKey(1), Link: out.Key}},
	}
	entryConfig := entry.compile(t, entrySnapshot)
	entryProcess := policylive.Start(t, entry.binary, append(entry.run, policylive.WriteFile(t, "entry.json", entryConfig.config))...)
	policylive.WaitListening(t, fmt.Sprintf("127.0.0.1:%d", entryPort), entryProcess)

	clientProcess := policylive.Start(t, client, "run", "-config", policylive.WriteFile(t, "client.json", clientConfig(t, socksPort, entryPort)))
	policylive.WaitListening(t, fmt.Sprintf("127.0.0.1:%d", socksPort), clientProcess)
	dump := func() string {
		return "entry:\n" + entryProcess.Output() + "\nexit:\n" + exitProcess.Output() + "\nclient:\n" + clientProcess.Output()
	}

	var exitMeter, entryMeter func() (agentcore.Counters, error)
	if exitConfig.meter != nil {
		exitMeter = exitConfig.meter(t)
	}
	if entryConfig.meter != nil {
		entryMeter = entryConfig.meter(t)
	}
	if err := socksTCP(socksPort, echo.Port, []byte("through the link")); err != nil {
		t.Fatalf("TCP through the link: %v\n%s", err, dump())
	}
	var udpErr error
	for attempt := 0; attempt < 5; attempt++ {
		if udpErr = socksUDP(socksPort, echo.Port, []byte("udp through the link")); udpErr == nil {
			break
		}
	}
	if udpErr != nil {
		t.Fatalf("UDP through the link: %v\n%s", udpErr, dump())
	}
	if err := socksTCP(socksPort, blocked.Port, []byte("must be blocked")); err == nil {
		t.Fatalf("the entry's block rule did not apply to a listener that leaves through a link\n%s", dump())
	}

	// A sing-box side meters the link itself: present, and at least the
	// payload in each direction. A sing-box entry still counts the user's
	// listener as well.
	const payload = int64(len("through the link"))
	waitCounters(t, "exit link", exitMeter, dump, func(c agentcore.Counters) bool {
		return linkReached(c, out.Key, payload)
	})
	waitCounters(t, "entry link", entryMeter, dump, func(c agentcore.Counters) bool {
		return linkReached(c, out.Key, payload) && len(c.Listeners) == 1 && c.Listeners[0].Present &&
			c.Listeners[0].UpBytes >= payload && c.Listeners[0].DownBytes >= payload
	})

	// Stop the exit: the entry must not fall back to its own address.
	exitProcess.Stop(t)
	if err := socksTCP(socksPort, echo.Port, []byte("no exit")); err == nil {
		t.Fatalf("with the exit stopped the connection still went through: the entry fell back to its own address\n%s", dump())
	}
}

